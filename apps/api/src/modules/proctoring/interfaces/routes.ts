import type { FastifyInstance } from 'fastify';
import { computeCheatingScore, shouldAutoFlag } from '@cbt/domain';
import { NotFoundError, PERMISSIONS, ForbiddenError } from '@cbt/shared';
import { requireAuth, requirePermission, sendError } from '../../../shared/auth-guards.js';
import { env } from '../../../config/env.js';
import { audit } from '../../../shared/audit.js';
import { mapProctorDetail, mapProctorLive } from '../../../shared/dto.js';
import { z } from 'zod';

const proctorEventSchema = z.object({
  type: z.enum([
    'FULLSCREEN_EXIT',
    'TAB_SWITCH',
    'DEVTOOLS_OPEN',
    'CLIPBOARD_COPY',
    'CLIPBOARD_PASTE',
    'RIGHT_CLICK',
    'SCREEN_CAPTURE',
    'FACE_MISSING',
    'MULTIPLE_FACES',
    'VOICE_DETECTED',
    'FOCUS_LOST',
    'FOCUS_GAINED',
    'MOUSE_IDLE',
    'KEYBOARD_IDLE',
    'IP_CHANGE',
    'DEVICE_CHANGE',
    'VPN_SUSPECTED',
    'LOCATION_CHANGE',
    'RECONNECT',
    'CUSTOM',
  ]),
  severity: z.number().int().min(1).max(10).default(1),
  payload: z.unknown().optional(),
  clientTimestamp: z.string().datetime().optional(),
});

export async function proctoringRoutes(app: FastifyInstance) {
  app.post(`${env.apiPrefix}/proctoring/events`, async (request, reply) => {
    try {
      const user = requireAuth(request);
      const body = proctorEventSchema
        .extend({ attemptId: z.string().uuid() })
        .parse(request.body);

      const attempt = await app.prisma.examAttempt.findUnique({
        where: { id: body.attemptId },
        include: { proctorSession: true },
      });
      if (!attempt?.proctorSession) throw new NotFoundError('Proctor session');
      if (attempt.userId !== user.id && !user.permissions.includes(PERMISSIONS.PROCTOR_MONITOR)) {
        throw new ForbiddenError();
      }

      const event = await app.prisma.proctorEvent.create({
        data: {
          proctorSessionId: attempt.proctorSession.id,
          type: body.type,
          severity: body.severity,
          payload: body.payload as object | undefined,
          clientTimestamp: body.clientTimestamp ? new Date(body.clientTimestamp) : null,
        },
      });

      if (body.type === 'FOCUS_LOST' || body.type === 'FOCUS_GAINED') {
        await app.prisma.focusEvent.create({
          data: {
            proctorSessionId: attempt.proctorSession.id,
            event: body.type,
          },
        });
      }

      const events = await app.prisma.proctorEvent.findMany({
        where: { proctorSessionId: attempt.proctorSession.id },
        select: { type: true, severity: true },
      });
      const score = computeCheatingScore(events);
      await app.prisma.proctorSession.update({
        where: { id: attempt.proctorSession.id },
        data: { cheatingScore: score },
      });

      if (shouldAutoFlag(score)) {
        const openFlag = await app.prisma.proctorFlag.findFirst({
          where: {
            proctorSessionId: attempt.proctorSession.id,
            resolvedAt: null,
            autoGenerated: true,
          },
        });
        if (!openFlag) {
          await app.prisma.proctorFlag.create({
            data: {
              proctorSessionId: attempt.proctorSession.id,
              reason: `Auto-flagged: cheating score ${score}`,
              severity: Math.min(10, Math.ceil(score / 10)),
              autoGenerated: true,
            },
          });
        }
      }

      await app.redis.publish(
        `proctor:session:${attempt.examSessionId}`,
        JSON.stringify({
          attemptId: attempt.id,
          event,
          cheatingScore: score,
        }),
      );

      await audit(app, {
        actorId: user.id,
        action: `proctor.${body.type.toLowerCase()}`,
        resource: 'proctor_event',
        resourceId: event.id,
        metadata: { attemptId: body.attemptId },
      });

      return reply.status(201).send({ event, cheatingScore: score });
    } catch (e) {
      return sendError(reply, e);
    }
  });

  app.post(`${env.apiPrefix}/proctoring/location`, async (request, reply) => {
    try {
      const user = requireAuth(request);
      const body = z
        .object({
          attemptId: z.string().uuid(),
          country: z.string().optional(),
          region: z.string().optional(),
          city: z.string().optional(),
          latitude: z.number().optional(),
          longitude: z.number().optional(),
          vpnSuspected: z.boolean().optional(),
          accuracy: z.number().optional(),
        })
        .parse(request.body);
      const attempt = await app.prisma.examAttempt.findUnique({
        where: { id: body.attemptId },
        include: {
          proctorSession: { include: { locationLogs: { orderBy: { createdAt: 'desc' }, take: 1 } } },
          examSession: { include: { examTemplate: true } },
        },
      });
      if (!attempt?.proctorSession || attempt.userId !== user.id) {
        throw new ForbiddenError();
      }

      const { lookupIpIntel } = await import('../ip-intel.js');
      const { haversineKm, resolveProctoringPolicy } = await import('../policy.js');
      const policy = resolveProctoringPolicy(
        attempt.examSession.examTemplate.mode,
        attempt.examSession.examTemplate.settings,
      );
      const intel = await lookupIpIntel(request.ip);
      const vpnSuspected =
        body.vpnSuspected ?? (policy.vpnCheck ? intel.vpnSuspected : false);

      const prev = attempt.proctorSession.locationLogs[0];
      const log = await app.prisma.locationLog.create({
        data: {
          proctorSessionId: attempt.proctorSession.id,
          ipAddress: intel.ip,
          country: body.country ?? intel.country,
          region: body.region ?? intel.region,
          city: body.city ?? intel.city,
          latitude: body.latitude ?? intel.latitude,
          longitude: body.longitude ?? intel.longitude,
          vpnSuspected,
        },
      });

      const events: Array<{ type: string; severity: number; payload?: object }> = [];

      if (prev && prev.ipAddress !== intel.ip) {
        events.push({
          type: 'IP_CHANGE',
          severity: 8,
          payload: { from: prev.ipAddress, to: intel.ip },
        });
      }

      if (
        prev?.latitude != null &&
        prev?.longitude != null &&
        body.latitude != null &&
        body.longitude != null
      ) {
        const km = haversineKm(
          Number(prev.latitude),
          Number(prev.longitude),
          body.latitude,
          body.longitude,
        );
        if (km > 25) {
          events.push({
            type: 'LOCATION_CHANGE',
            severity: 7,
            payload: { km: Math.round(km * 10) / 10, accuracy: body.accuracy },
          });
        }
      }

      if (vpnSuspected && !prev?.vpnSuspected) {
        events.push({
          type: 'VPN_SUSPECTED',
          severity: 8,
          payload: { org: intel.org, ip: intel.ip },
        });
      }

      for (const ev of events) {
        await app.prisma.proctorEvent.create({
          data: {
            proctorSessionId: attempt.proctorSession.id,
            type: ev.type as 'IP_CHANGE' | 'LOCATION_CHANGE' | 'VPN_SUSPECTED',
            severity: ev.severity,
            payload: ev.payload,
          },
        });
      }

      if (events.length) {
        const allEvents = await app.prisma.proctorEvent.findMany({
          where: { proctorSessionId: attempt.proctorSession.id },
          select: { type: true, severity: true },
        });
        const score = computeCheatingScore(allEvents);
        await app.prisma.proctorSession.update({
          where: { id: attempt.proctorSession.id },
          data: { cheatingScore: score },
        });
      }

      return reply.status(201).send({ log, eventsEmitted: events.map((e) => e.type) });
    } catch (e) {
      return sendError(reply, e);
    }
  });

  app.get(
    `${env.apiPrefix}/proctoring/live`,
    { preHandler: [requirePermission(PERMISSIONS.PROCTOR_MONITOR)] },
    async (request, reply) => {
      try {
        const q = request.query as { sessionId?: string };
        const sessions = await app.prisma.proctorSession.findMany({
          where: {
            status: 'ACTIVE',
            ...(q.sessionId
              ? { attempt: { examSessionId: q.sessionId } }
              : {}),
          },
          include: {
            attempt: {
              include: {
                user: { select: { id: true, firstName: true, lastName: true, email: true } },
                examSession: { select: { id: true, name: true } },
              },
            },
            flags: { where: { resolvedAt: null }, take: 5 },
            _count: { select: { events: true } },
          },
          orderBy: { cheatingScore: 'desc' },
          take: 200,
        });
        return reply.send({ data: sessions.map(mapProctorLive) });
      } catch (e) {
        return sendError(reply, e);
      }
    },
  );

  app.get(
    `${env.apiPrefix}/proctoring/attempts/:attemptId`,
    { preHandler: [requirePermission(PERMISSIONS.PROCTOR_MONITOR)] },
    async (request, reply) => {
      try {
        const { attemptId } = request.params as { attemptId: string };
        const session = await app.prisma.proctorSession.findUnique({
          where: { attemptId },
          include: {
            events: { orderBy: { createdAt: 'desc' }, take: 200 },
            flags: { orderBy: { createdAt: 'desc' } },
            focusEvents: { orderBy: { createdAt: 'desc' }, take: 100 },
            locationLogs: { orderBy: { createdAt: 'desc' }, take: 20 },
            attempt: {
              include: {
                user: { select: { id: true, firstName: true, lastName: true, email: true } },
                examSession: { include: { examTemplate: { select: { title: true } } } },
              },
            },
          },
        });
        if (!session) throw new NotFoundError('Proctor session');
        return reply.send(mapProctorDetail(session));
      } catch (e) {
        return sendError(reply, e);
      }
    },
  );

  app.post(
    `${env.apiPrefix}/proctoring/flags/:flagId/resolve`,
    { preHandler: [requirePermission(PERMISSIONS.PROCTOR_MANAGE)] },
    async (request, reply) => {
      try {
        const user = requireAuth(request);
        const { flagId } = request.params as { flagId: string };
        const body = z.object({ notes: z.string().optional() }).parse(request.body ?? {});
        const flag = await app.prisma.proctorFlag.update({
          where: { id: flagId },
          data: {
            resolvedAt: new Date(),
            resolvedById: user.id,
            notes: body.notes,
          },
        });
        return reply.send(flag);
      } catch (e) {
        return sendError(reply, e);
      }
    },
  );
}
